// 16 进制色 → [r,g,b]；支持 3 位缩写（#f00）与 6 位（#ff0000），非法返回 null
function hexToRgb(hex) {
  var h = (hex || '').replace('#', '');
  if (h.length === 3) h = h[0] + h[0] + h[1] + h[1] + h[2] + h[2];
  var n = parseInt(h, 16);
  if (h.length !== 6 || isNaN(n)) return null;
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}
